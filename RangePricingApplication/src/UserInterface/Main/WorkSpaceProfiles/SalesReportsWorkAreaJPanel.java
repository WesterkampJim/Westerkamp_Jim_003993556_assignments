    private void clearTable(){
        DefaultTableModel model = (DefaultTableModel) jSalesReportsTable.getModel();
        int rowCount = jSalesReportsTable.getRowCount();
        model.setColumnCount(0);
        for(int i=rowCount-1;i>=0;i--){
            model.removeRow(i);
        }
    }
    
    
    
    
    

