    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed

        String nuid = txtNUID.getText();
        String username = txtUsername.getText();
        String name = txtName.getText();
        String password = txtPassword.getText();


        if (name.trim().isBlank() || nuid.trim().isBlank() || username.trim().isBlank()|| password.trim().isBlank()) {
            JOptionPane.showMessageDialog(this, "All fields are mandatory.",
                    "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!username.matches("[A-Za-z0-9 ._-]+") || username.length() > 25 ) {
            JOptionPane.showMessageDialog(this,"Username must be 1–25 characters and may contain letters, numbers, periods, underscores, and hyphens.","Invalid Username", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (!name.matches("[A-Za-z0-9 ._-]+") || username.length() > 25 ) {
            JOptionPane.showMessageDialog(this,"Name must be 1–25 characters and may contain letters, numbers, periods, underscores, and hyphens.","Invalid Username", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (!nuid.matches("[A-Za-z0-9 ._-]+") || nuid.length() > 25 ) {
            JOptionPane.showMessageDialog(this,"NUID must be 1–25 characters and may contain letters, numbers, periods, underscores, and hyphens.","Invalid Username", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (!password.matches("[A-Za-z0-9 ._-]+") || password.length() > 25 ) {
            JOptionPane.showMessageDialog(this,"password must be 1–25 characters and may contain letters, numbers, periods, underscores, and hyphens.","Invalid Username", JOptionPane.ERROR_MESSAGE);
            return;
        }


        // check the role combo box, then see if that person ID exists in any of the directories already.
        
        UserAccountDirectory accounts = business.getUserAccountDirectory();
        for (UserAccount account : accounts.getUserAccountList()) {
            if (account.getUserLoginName().equalsIgnoreCase(username)) {
                JOptionPane.showMessageDialog(this, "That username is already in use.","Duplicate Username", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        
        StudentDirectory students = business.getStudentDirectory();
        for (StudentProfile s : students.getStudentList()) {
            if (s.getNUID().equalsIgnoreCase(nuid)) {
                JOptionPane.showMessageDialog(this, "That NUID is already in use.","Duplicate NUID", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        
        
        Person p = business.getPersonDirectory().newPerson(name);
        Profile newprofile = business.getStudentDirectory().newStudentProfile(p);   
        UserAccount ua = business.getUserAccountDirectory().newUserAccount(newprofile, username.trim(), password); 
        ua.setStatus("Active");
        //cast to student profile so we can add nuid.
        StudentProfile sp =(StudentProfile) ua.getAssociatedPersonProfile();
        sp.setNUID(nuid);
        
        
        JOptionPane.showMessageDialog(this, "User account successfully created.","Information", JOptionPane.INFORMATION_MESSAGE);
        
        
        

            
        StudentWorkAreaJPanel studentworkareajpanel;
       // String r = useraccount.getRole();
        Profile profile = ua.getAssociatedPersonProfile();
        StudentProfile spp = (StudentProfile) profile;
        studentworkareajpanel = new StudentWorkAreaJPanel(business, spp, CardSequencePanel, ua);
        CardSequencePanel.removeAll();
        CardSequencePanel.add("student", studentworkareajpanel);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);


        
        
        
        
    }//GEN-LAST:event_btnUpdateActionPerformed


