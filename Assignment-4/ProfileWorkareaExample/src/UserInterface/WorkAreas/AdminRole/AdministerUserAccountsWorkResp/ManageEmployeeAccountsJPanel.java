    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
    String searchText = txtSearchBox.getText().trim();

    // No blank terms allowed.
    if (searchText.isBlank()) {
        JOptionPane.showMessageDialog(this,"Please type a term to search.","Warning",JOptionPane.WARNING_MESSAGE);
        return;
    }
    // Reset table.
    DefaultTableModel model =(DefaultTableModel) UserAccountTable.getModel();
    model.setRowCount(0);

    // Check whether any students match.
    boolean foundItems = false;
    // Search.
    for (EmployeeProfile employee : business.getEmployeeDirectory().getEmployeeList()) {
            // Find the student's associated user account.
            for (UserAccount account : business.getUserAccountDirectory().getUserAccountList()) {

                if (employee.getPerson().getPersonId().equalsIgnoreCase(searchText)|| account.getUserLoginName().equalsIgnoreCase(searchText)){

                    if (account.getAssociatedPersonProfile() == employee) {
                    Object[] row = new Object[5];

                    row[0] = account;
                    row[1] = account.getStatus();
                    row[2] = employee.getJobTitle();
                    row[3] = account.getLastAccessed();
                    row[4] = account.getLastUpdated();

                    model.addRow(row);
                    foundItems = true;
                 }
            }
        }
    }

    if (!foundItems) {
        JOptionPane.showMessageDialog(this,
                "No employee account found matching your search.",
                "Warning",
                JOptionPane.WARNING_MESSAGE);

        refreshTable();
    }
    
    }//GEN-LAST:event_btnSearchActionPerformed
    
    
    

