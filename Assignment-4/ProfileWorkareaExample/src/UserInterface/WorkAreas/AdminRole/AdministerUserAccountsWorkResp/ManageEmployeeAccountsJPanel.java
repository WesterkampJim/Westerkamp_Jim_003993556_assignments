public void refreshTable() {
    DefaultTableModel model =(DefaultTableModel) UserAccountTable.getModel();
    model.setRowCount(0);
    UserAccountDirectory uad = business.getUserAccountDirectory();
    for (UserAccount ua : uad.getUserAccountList()) {
        if (ua.getAssociatedPersonProfile() instanceof EmployeeProfile) {
               ///Only pull in users with employee profiles.
            EmployeeProfile employee =(EmployeeProfile) ua.getAssociatedPersonProfile();

            Object[] row = new Object[5];
            row[0] = ua;
            row[1] = ua.getStatus();
            row[2] = employee.getJobTitle();
            row[3] = ua.getLastAccessed();
            row[4] = ua.getLastUpdated();

            model.addRow(row);
        }
    }
}

    
