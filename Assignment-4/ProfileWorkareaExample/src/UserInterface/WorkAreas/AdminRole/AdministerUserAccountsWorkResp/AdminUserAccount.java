    private void UpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateActionPerformed
        // TODO add your handling code here:
        String personId = (String) cmbPerson.getSelectedItem();
        String role = (String) cmbProfile.getSelectedItem();
        String username = txtUsername.getText().trim();
        String password = txtPassword.getText();
        String status = txtStatus.getText();
        String nuid = txtNUID.getText();

        if (personId == null || role == null || username.isBlank()) {
            JOptionPane.showMessageDialog(this, "Person, profile, and username are required.","ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (!username.matches("[A-Za-z0-9 ._-]+") || username.length()>25) {
            JOptionPane.showMessageDialog(this,
                    "Username must be 1–25 characters and may contain letters, numbers, periods, underscores, and hyphens.","Invalid Username", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (password.length() > 20) {
            JOptionPane.showMessageDialog(this, "Password must be 20 characters or fewer.","Invalid Password", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (nuid.length() > 20) {
            JOptionPane.showMessageDialog(this, "Password must be 20 characters or fewer.","Invalid Password", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (status.length() > 20) {
            JOptionPane.showMessageDialog(this, "Status must be 20 characters or fewer.","Invalid Status", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Person person = business.getPersonDirectory().findPerson(personId);
        if (person == null) {
            JOptionPane.showMessageDialog(this, "The selected person could not be found.","Person Not Found", JOptionPane.ERROR_MESSAGE);
            return;
        }

        for (UserAccount account : business.getUserAccountDirectory().getUserAccountList()) {
            if (account != selecteduseraccount
                    && account.getUserLoginName().equalsIgnoreCase(username)) {
                JOptionPane.showMessageDialog(this, "That username is already in use.","Duplicate Username", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        Profile oldProfile = selecteduseraccount.getAssociatedPersonProfile();
        String oldRole = getProfileType(oldProfile);
        Profile newProfile =null;
        ///look for existing profile from this person in directories.
        if ("Employee".equalsIgnoreCase(role)) {
            newProfile =  business.getEmployeeDirectory().findEmployee(personId);
        }
        if ("Student".equalsIgnoreCase(role)) {
            newProfile = business.getStudentDirectory().findStudent(personId);
        }
        if ("Faculty".equalsIgnoreCase(role)) {
            newProfile = business.getFacultyDirectory().findFaculty(personId);
        }
        //if the person is already assigned to a profile, return
        if (newProfile != null && newProfile != oldProfile) {
            for (UserAccount account : business.getUserAccountDirectory().getUserAccountList()) {
                if (account != selecteduseraccount && account.getAssociatedPersonProfile() == newProfile) {
                    JOptionPane.showMessageDialog(this,"That person already has a user account.","Duplicate Account", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
        }
        
        // students can't have employment information.
        if ("Student".equals(role)) {
            if (!txtJobTitle.getText().trim().isBlank() || !txtHourlyRate.getText().trim().isBlank() || chkTenured.isSelected()) {

                JOptionPane.showMessageDialog(this,
                        "Employment information cannot be given to a Student profile.","Invalid Employment Information", JOptionPane.ERROR_MESSAGE);
                return;
            }}
        
        if (newProfile == null) {
            if ("Employee".equalsIgnoreCase(role)) {
                    newProfile =  business.getEmployeeDirectory().newEmployeeProfile(person);
                }else if ("Student".equalsIgnoreCase(role)) {
                    newProfile =  business.getStudentDirectory().newStudentProfile(person);
                }else if ("Faculty".equalsIgnoreCase(role)) {
                    newProfile =  business.getFacultyDirectory().newFacultyProfile(person);
            } 
        }

        if (!role.equals(oldRole)) {
            deleteProfile(oldProfile);
        }
        
           
        selecteduseraccount.setAssociatedPersonProfile(newProfile);
        selecteduseraccount.setUserName(username);
        selecteduseraccount.setStatus(status);
        
        //only apply nuid to students
        if (!nuid.isBlank()){
            StudentDirectory students = business.getStudentDirectory();
            for (StudentProfile s : students.getStudentList()) {
                if (s.getNUID()!=null){
                if (s.getNUID().equalsIgnoreCase(nuid)) {
                    JOptionPane.showMessageDialog(this, "That NUID is already in use.","Duplicate NUID", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                }
            }

            if(selecteduseraccount.getAssociatedPersonProfile()instanceof StudentProfile){
                StudentProfile sp = (StudentProfile) selecteduseraccount.getAssociatedPersonProfile();
                sp.setNUID(nuid);
            }
        }
        
        //only update if changed.
        if (!password.isEmpty()) {
            selecteduseraccount.setPassword(password);
        }
        
        
        
        ////Faculty and Employee inputs
        if (newProfile instanceof EmployeeProfile || newProfile instanceof FacultyProfile) {

            String jobTitle = txtJobTitle.getText().trim();
            String hourlyRateText = txtHourlyRate.getText().trim();
            boolean isTenured = chkTenured.isSelected();

            if (jobTitle.length() > 50) {JOptionPane.showMessageDialog(this,"Job title must be 50 characters or less.","Invalid Job Title", JOptionPane.ERROR_MESSAGE);
                return;
            }

            float hourlyRate = 0;

            //validate hourly rate
            if (!hourlyRateText.isEmpty()) {
                try { ///check if input was float formatted
                    hourlyRate = Float.parseFloat(hourlyRateText);

                    if (hourlyRate < 0 ) {
                        JOptionPane.showMessageDialog(this,"Hourly rate must be non-negative number, decimals allowed.","Invalid Hourly Rate", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this,"Hourly rate must be a valid number.","Invalid Hourly Rate", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }
       
                 //if this is an employee or faculty, populate in the employee and faculty specific fields.          
              if (newProfile instanceof EmployeeProfile) {
                    EmployeeProfile employee = (EmployeeProfile) newProfile;
                    employee.setJobTitle(jobTitle);
                    employee.setHourlyWage(hourlyRate);
                    employee.setTenured(isTenured);

                } else if (newProfile instanceof FacultyProfile) {
                    FacultyProfile faculty = (FacultyProfile) newProfile;
                    faculty.setJobTitle(jobTitle);
                    faculty.setHourlyWage(hourlyRate);
                    faculty.setTenured(isTenured);
                }
 
            
        }/// end of faculty and employee only code

            ///success
        JOptionPane.showMessageDialog(this, "User account successfully updated.","Information", JOptionPane.INFORMATION_MESSAGE);
    

    }//GEN-LAST:event_UpdateActionPerformed

    ///delete profile from directory 
    private void deleteProfile(Profile profile) {
        if (profile instanceof EmployeeProfile) {
            business.getEmployeeDirectory().removeEmployeeProfile((EmployeeProfile) profile);
        } else if (profile instanceof StudentProfile) {
            business.getStudentDirectory().removeStudentProfile((StudentProfile) profile);
        } else if (profile instanceof FacultyProfile) {
            business.getFacultyDirectory().removeFacultyProfile((FacultyProfile) profile);
        }
    }
    
